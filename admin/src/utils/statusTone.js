function normalizeStatus(status) {
  return String(status || '').trim().toLowerCase().replace(/[_-]+/g, ' ').replace(/\s+/g, ' ');
}

export function getStatusToneColors(status) {
  return TONE_COLORS[STATUS_TONES[normalizeStatus(status)] || 'inactive'];
}
