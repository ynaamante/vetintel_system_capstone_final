import assert from 'node:assert/strict';
import { createApiFetch } from '../admin/src/utils/apiFetch.js';

let calls = 0;
let clock = 0;
let status = 200;
let release;
let hold = false;
const network = async () => {
  const number = ++calls;
  if (hold) await new Promise(resolve => { release = resolve; });
  return Response.json({ number }, { status });
};
const client = createApiFetch(network, { baseUrl: '/api', origin: 'http://localhost', now: () => clock });
const headers = { Authorization: 'Bearer user-a' };
const get = (path = '/api/clinic-records/pets', options = {}) => client.fetch(path, { headers, ...options });

const first = await get();
assert.equal((await first.json()).number, 1);
assert.equal((await (await get()).json()).number, 1, 'returning to a page reuses its data');
assert.equal(calls, 1);
clock = 30001;
await get();
assert.equal(calls, 2, 'expired data reaches the server');
await get('/api/clinic-records/pets?clinic_id=2');
assert.equal(calls, 3, 'different filters/clinics have separate entries');
await get('/api/me');
await get('/api/me');
assert.equal(calls, 5, 'permissions always reach the server');
await get('/api/clinic-records/pets', { cache: 'no-store' });
assert.equal(calls, 6, 'explicit fresh reads bypass the cache');
await get('/api/clinic-records/pets', { method: 'POST', body: '{}' });
await get();
assert.equal(calls, 8, 'writes invalidate old page data');
await get('/api/clinic-records/pets', { headers: { Authorization: 'Bearer user-b' } });
assert.equal(calls, 9, 'sessions never share cached data');
await get();
assert.equal(calls, 10);

client.clear();
hold = true;
const controller = new AbortController();
const leftPage = get(undefined, { signal: controller.signal });
const nextPage = get();
const aborted = assert.rejects(leftPage, { name: 'AbortError' });
controller.abort();
release();
await aborted;
assert.equal((await (await nextPage).json()).number, 11);
assert.equal(calls, 11, 'concurrent reads share one request with independent cancellation');
hold = false;

client.clear();
hold = true;
const oldRequest = get();
client.clear();
release();
await oldRequest;
hold = false;
await get();
assert.equal(calls, 13, 'invalidated in-flight reads cannot repopulate the cache');

status = 403;
await get('/api/me');
status = 200;
await get();
assert.equal(calls, 15, 'denied permission checks discard cached data');
client.clear();
status = 500;
await get();
await get();
assert.equal(calls, 17, 'errors are never cached');
status = 200;
await get('/api/clinic-records/events');
await get('/api/clinic-records/events');
assert.equal(calls, 19, 'live event streams bypass caching');
await get('https://other.example/api/clinic-records/pets');
await get('https://other.example/api/clinic-records/pets');
assert.equal(calls, 21, 'unrelated origins bypass caching');
console.log('PASS: navigation reuse, expiry, filters, permissions, writes, session isolation, cancellation, in-flight invalidation, errors, streams, and external requests');
